def output_prefix() -> str:
    return "weather-logistics-historical-baseline"


def build_outputs(request_path: Path = DEFAULT_REQUEST) -> dict[str, Any]:
    _schema_path, schema_errors = validate_file(request_path, SPEC / "forecast-request.schema.json")
    if schema_errors:
        raise HistoricalBaselineError(f"request contract validation failed: {schema_errors[0]}")
    request = load_json(request_path)
    decision = validate_request(request)
    if decision["decisionStatus"] != "accepted":
        raise HistoricalBaselineError(f"request was {decision['decisionStatus']}")
    if request["requestedAction"] != "generate_forecast":
        raise HistoricalBaselineError("historical baseline forecast requires requestedAction generate_forecast")
    if request["dataMode"] != "provided":
        raise HistoricalBaselineError("historical baseline forecast requires dataMode provided")
    if set(request["sourcePolicy"]["allowedConnectors"]) != {"committed_fixture"}:
        raise HistoricalBaselineError("historical baseline forecast requires only the committed_fixture connector")
    if request["sourcePolicy"]["allowNetworkAccess"] or request["sourcePolicy"]["maxNetworkCalls"] != 0:
        raise HistoricalBaselineError("historical baseline forecast must not allow network access")

    baseline = build_baseline(request, load_json(BASELINE_HISTORY))
    question = build_question(request, baseline)
    feature_snapshot = build_feature_snapshot(request, question, baseline)
    evidence = build_evidence_packet(request, question, baseline)
    artifact = build_forecast_artifact(question, evidence)
    history = build_history(question, baseline, evidence)
    pipeline_run = build_pipeline_run(request, decision, question, evidence, history)
    prefix = output_prefix()
    outputs = {
        f"{prefix}-pipeline-run.generated.json": pipeline_run,
        f"{prefix}-question.generated.json": question,
        f"{prefix}-feature-snapshot.generated.json": feature_snapshot,
        f"{prefix}-evidence.generated.json": evidence,
        f"{prefix}-artifact.generated.json": artifact,
        f"{prefix}-history.generated.json": history,
    }
    validate_outputs(outputs)
    return outputs


def validate_outputs(outputs: dict[str, Any]) -> None:
    prefix = output_prefix()
    schemas = {
        f"{prefix}-pipeline-run.generated.json": "pipeline-run.schema.json",
        f"{prefix}-question.generated.json": "forecast-question.schema.json",
        f"{prefix}-evidence.generated.json": "evidence-packet.schema.json",
        f"{prefix}-artifact.generated.json": "forecast-artifact.schema.json",
        f"{prefix}-history.generated.json": "forecast-history.schema.json",
    }
    for filename, schema_name in schemas.items():
        errors = validate_record(outputs[filename], SPEC / schema_name)
        if errors:
            raise HistoricalBaselineError(f"{filename} failed schema validation: {errors[0]}")

    pipeline_run = outputs[f"{prefix}-pipeline-run.generated.json"]
    question = outputs[f"{prefix}-question.generated.json"]
    feature_snapshot = outputs[f"{prefix}-feature-snapshot.generated.json"]
    evidence = outputs[f"{prefix}-evidence.generated.json"]
    artifact = outputs[f"{prefix}-artifact.generated.json"]
    history = outputs[f"{prefix}-history.generated.json"]

    if artifact["forecastOutput"] != artifact["baselineForecast"]:
        raise HistoricalBaselineError("historical-only forecast output must equal baseline output")
    if evidence["forecastOutput"] != evidence["baselineForecast"]:
        raise HistoricalBaselineError("historical-only evidence output must equal baseline output")
    if pipeline_run["outputs"]["forecastId"] != artifact["forecastId"]:
        raise HistoricalBaselineError("pipeline run/forecast binding mismatch")
    if pipeline_run["outputs"]["questionId"] != question["questionId"]:
        raise HistoricalBaselineError("pipeline run/question binding mismatch")
    if artifact["forecastId"] != evidence["forecastId"]:
        raise HistoricalBaselineError("artifact/evidence forecast binding mismatch")
    if artifact["questionId"] != question["questionId"]:
        raise HistoricalBaselineError("artifact/question binding mismatch")
    if history["entries"][-1]["forecastId"] != evidence["forecastId"]:
        raise HistoricalBaselineError("history must end with the historical baseline forecast")
    if history["entries"][-1]["sourceClass"] != "baseline":
        raise HistoricalBaselineError("historical-only forecast history must remain baseline-sourced")
    if "forecastDailyPrecipitationMm" in feature_snapshot["features"]:
        raise HistoricalBaselineError("historical-only features must not include forecast-time weather data")
    if any(source["sourceType"] != "internal_dataset" for source in evidence["provenanceReferences"]):
        raise HistoricalBaselineError("historical-only provenance must use internal historical data only")
    if pipeline_run["controls"]["networkAccess"] or pipeline_run["controls"]["liveFetch"]:
        raise HistoricalBaselineError("historical-only pipeline must not use network or live fetch")


def write_outputs(outputs: dict[str, Any]) -> None:
    expected_names = set(outputs)
    GENERATED.mkdir(parents=True, exist_ok=True)
    for path in GENERATED.glob("*.generated.json"):
        if path.name not in expected_names:
            path.unlink()
    for filename, output in outputs.items():
        write_json(GENERATED / filename, output)
    print(f"generated {len(outputs)} historical baseline forecast outputs")


def check_outputs(outputs: dict[str, Any]) -> None:
    errors: list[str] = []
    expected_names = set(outputs)
    for path in sorted(GENERATED.glob("*.generated.json")):
        if path.name not in expected_names:
            errors.append(f"stale historical baseline output: {path}")
    for filename, output in outputs.items():
        path = GENERATED / filename
        expected = render_json(output)
        if not path.exists():
            errors.append(f"missing historical baseline output: {path}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(f"historical baseline drift: {path}")
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("run `python3 scripts/run_historical_baseline_forecast.py --write`", file=sys.stderr)
        raise SystemExit(1)
    print(f"checked {len(outputs)} historical baseline forecast outputs")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--request", type=Path, default=DEFAULT_REQUEST)
    parser.add_argument("--write", action="store_true", help="write generated historical baseline outputs")
    args = parser.parse_args()
    try:
        outputs = build_outputs(args.request)
    except HistoricalBaselineError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
    if args.write:
        write_outputs(outputs)
    else:
        check_outputs(outputs)


if __name__ == "__main__":
    main()

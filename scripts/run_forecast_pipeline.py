ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REQUEST = ROOT / "spec" / "fixtures" / "requests" / "generate-weather-logistics-request.json"
WEATHER_FORECAST = ROOT / "spec" / "fixtures" / "live" / "open-meteo-warsaw-forecast-response.json"
BASELINE_HISTORY = ROOT / "spec" / "fixtures" / "source" / "weather-logistics-warsaw-2026-06-03" / "baseline-history.json"
GENERATED = ROOT / "spec" / "fixtures" / "generated" / "pipeline"
FORECAST_RETRIEVED_AT = "2026-06-02T09:30:00Z"
FORECASTED_AT = "2026-06-02T10:00:00Z"
GENERATED_AT = "2026-06-02T10:01:00Z"


class PipelineRejected(Exception):
    pass


def render_json(data: Any) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_json(data), encoding="utf-8")


def pipeline_prefix(_request: dict[str, Any]) -> str:
    return "weather-logistics-pipeline"


def source_ref(source_id: str, name: str, source_type: str) -> dict[str, str]:
    return {
        "sourceId": source_id,
        "name": name,
        "sourceType": source_type,
    }


def assert_request_executable(request: dict[str, Any], decision: dict[str, Any]) -> None:
    if decision["decisionStatus"] != "accepted":
        raise PipelineRejected(f"request {request['requestId']} was {decision['decisionStatus']}")
    if request["requestedAction"] != "generate_forecast":
        raise PipelineRejected("pipeline requires requestedAction generate_forecast")


def build_normalized_weather(request: dict[str, Any]) -> dict[str, Any]:
    payload, raw = load_fixture(WEATHER_FORECAST)
    return normalize_response(
        payload=payload,
        raw=raw,
        source_url=build_url("warsaw", request["serviceDate"]),
        retrieved_at=FORECAST_RETRIEVED_AT,
        location_key="warsaw",
        service_date=request["serviceDate"],
    )



def build_outputs(request_path: Path = DEFAULT_REQUEST) -> dict[str, Any]:
    _schema_path, schema_errors = validate_file(request_path, SPEC / "forecast-request.schema.json")
    if schema_errors:
        raise PipelineRejected(f"request contract validation failed: {schema_errors[0]}")
    request = load_json(request_path)
    decision = validate_request(request)
    assert_request_executable(request, decision)

    normalized_weather = build_normalized_weather(request)
    baseline = build_baseline_record(
        normalized_weather=normalized_weather,
        baseline_history=load_json(BASELINE_HISTORY),
        generated_at=FORECASTED_AT,
    )
    operations_source = source_ref(
        "source-402",
        "Declared Warsaw operations event source",
        "internal_dataset",
    )
    weather_observation_source = source_ref(
        "source-403",
        "Open-Meteo weather observation for Warsaw",
        "public_dataset",
    )
    question = build_question(request, baseline, operations_source, weather_observation_source)
    feature_snapshot = build_feature_snapshot(request, question, baseline)
    forecast_output = {
        "outputType": "binary",
        "probability": model_probability(baseline),
    }
    evidence = build_evidence_packet(
        request,
        question,
        baseline,
        forecast_output,
        operations_source,
        weather_observation_source,
    )
    artifact = build_forecast_artifact(question, evidence)
    history = build_history(question, baseline, evidence)
    pipeline_run = build_pipeline_run(request, decision, question, evidence, history)
    prefix = pipeline_prefix(request)
    outputs = {
        f"{prefix}-pipeline-run.generated.json": pipeline_run,
        f"{prefix}-question.generated.json": question,
        f"{prefix}-feature-snapshot.generated.json": feature_snapshot,
        f"{prefix}-evidence.generated.json": evidence,
        f"{prefix}-artifact.generated.json": artifact,
        f"{prefix}-history.generated.json": history,
    }
    validate_outputs(outputs)
    return outputs


def validate_outputs(outputs: dict[str, Any]) -> None:
    pipeline_run = outputs["weather-logistics-pipeline-pipeline-run.generated.json"]
    question = outputs["weather-logistics-pipeline-question.generated.json"]
    evidence = outputs["weather-logistics-pipeline-evidence.generated.json"]
    artifact = outputs["weather-logistics-pipeline-artifact.generated.json"]
    history = outputs["weather-logistics-pipeline-history.generated.json"]

    if pipeline_run["outputs"]["questionId"] != question["questionId"]:
        raise AssertionError("pipeline run/question binding mismatch")
    if pipeline_run["outputs"]["forecastId"] != evidence["forecastId"]:
        raise AssertionError("pipeline run/evidence binding mismatch")
    if artifact["forecastId"] != evidence["forecastId"]:
        raise AssertionError("pipeline artifact/evidence forecast binding mismatch")
    if artifact["questionId"] != question["questionId"]:
        raise AssertionError("pipeline artifact/question binding mismatch")
    if history["entries"][-1]["forecastId"] != evidence["forecastId"]:
        raise AssertionError("pipeline history must end with generated model forecast")

    forecast_source_ids = {source["sourceId"] for source in evidence["provenanceReferences"]}
    resolution_source_ids = {
        question["primaryResolutionSource"]["sourceId"],
        *[source["sourceId"] for source in question["fallbackResolutionSources"]],
    }
    if forecast_source_ids.intersection(resolution_source_ids):
        raise AssertionError("pipeline forecast provenance must not include future resolution sources")
    if pipeline_run["effectfulGeneration"] is not False:
        raise AssertionError("local fixture pipeline must not claim effectful generation")


def write_outputs(outputs: dict[str, Any]) -> None:
    expected_names = set(outputs)
    for path in GENERATED.glob("*.generated.json"):
        if path.name not in expected_names:
            path.unlink()
    for filename, output in outputs.items():
        write_json(GENERATED / filename, output)
    print(f"generated {len(outputs)} forecast pipeline outputs")


def check_outputs(outputs: dict[str, Any]) -> None:
    errors: list[str] = []
    expected_names = set(outputs)
    for path in sorted(GENERATED.glob("*.generated.json")):
        if path.name not in expected_names:
            errors.append(f"stale forecast pipeline output: {path}")
    for filename, output in outputs.items():
        path = GENERATED / filename
        expected = render_json(output)
        if not path.exists():
            errors.append(f"missing forecast pipeline output: {path}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(f"forecast pipeline drift: {path}")
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("run `python3 scripts/run_forecast_pipeline.py --write`", file=sys.stderr)
        raise SystemExit(1)
    print(f"checked {len(outputs)} forecast pipeline outputs")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--request", type=Path, default=DEFAULT_REQUEST)
    parser.add_argument("--write", action="store_true", help="write generated pipeline outputs")
    args = parser.parse_args()
    try:
        outputs = build_outputs(args.request)
    except PipelineRejected as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
    if args.write:
        write_outputs(outputs)
    else:
        check_outputs(outputs)


if __name__ == "__main__":
    main()

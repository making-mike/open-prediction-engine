#!/usr/bin/env python3
"""Run or check the fixture-only OPE evidence loop."""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

from ope_scoring import (
    baseline_lift,
    calibration_buckets,
    score_forecast_output,
    should_exclude_resolution,
    track_record_summary,
)
from ope_fixtures import render_json


ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / "spec" / "fixtures" / "source"
GENERATED = ROOT / "spec" / "fixtures" / "generated" / "fixture-loop"
GENERATED_AT = "2026-06-04T10:20:00Z"


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_json(data), encoding="utf-8")


def round_float(value: float | None) -> float | None:
    if value is None:
        return None
    return round(value, 10)


def parse_time(value: str) -> datetime:
    if value.endswith("Z"):
        value = value[:-1] + "+00:00"
    return datetime.fromisoformat(value)


def output_prefix(case: dict[str, Any]) -> str:
    return str(case.get("outputPrefix", "weather-logistics"))


def generated_at(case: dict[str, Any]) -> str:
    return str(case.get("generatedAt", GENERATED_AT))


def expected_calibration_error(buckets: list[dict[str, Any]], sample_size: int) -> float:
    if sample_size == 0:
        return 0.0
    return sum(
        bucket["count"]
        / sample_size
        * abs(bucket["meanForecastProbability"] - bucket["observedFrequency"])
        for bucket in buckets
    )


def baseline_probability(baseline: dict[str, Any]) -> float:
    comparable_days = int(baseline["comparableServiceDays"])
    if comparable_days <= 0:
        raise ValueError("baseline comparableServiceDays must be positive")
    return round(float(baseline["disruptionDays"]) / comparable_days, 2)


def model_probability(base_probability: float, feature_snapshot: dict[str, Any]) -> float:
    features = feature_snapshot["features"]
    adjustment = 0.19 if features["forecastExceedsThreshold"] else -0.07
    if features["routeDensity"] == "high":
        adjustment += 0.04
    if features["routeDensity"] == "low":
        adjustment -= 0.04
    return round(min(0.95, max(0.01, base_probability + adjustment)), 2)


def build_question(case: dict[str, Any], operations: dict[str, Any], weather: dict[str, Any]) -> dict[str, Any]:
    threshold = case["precipitationThresholdMm"]
    service_date = case["serviceDate"]
    geography = case["geography"]
    return {
        "questionId": case["questionId"],
        "title": f"Will heavy rain disrupt last-mile delivery operations in {geography} on {service_date}?",
        "background": "Generated by the fixture-only evidence loop for the selected weather-logistics wedge.",
        "domain": case["domain"],
        "outputType": "binary",
        "status": case.get("resolutionStatus", "resolved"),
        "openAt": case["openAt"],
        "closeAt": case["closeAt"],
        "resolveAt": case["resolveAt"],
        "horizon": case["horizon"],
        "resolutionCriteria": (
            "Resolve Yes if the declared operations fixture reports at least one weather-coded "
            f"delivery disruption in {geography} on {service_date} and the weather fixture records "
            f"daily precipitation of at least {threshold} millimeters. Resolve No otherwise."
        ),
        "resolutionAuthority": "OPE fixture resolver",
        "resolutionMode": "automated_measurement",
        "primaryResolutionSource": operations["sourceRef"],
        "fallbackResolutionSources": [weather["observationSourceRef"]],
        "validOutcomeSpace": {
            "description": "Binary outcome: Yes if the disruption and precipitation conditions are both satisfied; No otherwise.",
            "labels": ["yes", "no"],
        },
        "clarificationHistory": [],
        "incentiveRiskReview": {
            "riskLevel": "minimal",
            "notes": "Synthetic fixture data with no live operational exposure.",
        },
        "createdAt": case["openAt"],
        "updatedAt": case["resolvedAt"],
    }


def build_normalized_sources(
    case: dict[str, Any],
    operations: dict[str, Any],
    weather: dict[str, Any],
    baseline: dict[str, Any],
) -> dict[str, Any]:
    case_generated_at = generated_at(case)
    return {
        "normalizedSourceSetId": case["normalizedSourceSetId"],
        "caseId": case["caseId"],
        "generatedAt": case_generated_at,
        "domain": case["domain"],
        "geography": case["geography"],
        "serviceDate": case["serviceDate"],
        "records": [
            {
                "sourceRole": "forecast_input",
                "sourceRef": weather["forecastSourceRef"],
                "normalizedFields": {
                    "forecastDailyPrecipitationMm": weather["forecast"]["dailyPrecipitationMm"],
                    "forecastIssuedAt": weather["forecast"]["issuedAt"],
                    "warningLevel": weather["forecast"]["warningLevel"],
                },
            },
            {
                "sourceRole": "resolution_support",
                "sourceRef": weather["observationSourceRef"],
                "normalizedFields": {
                    "observedDailyPrecipitationMm": weather["observation"]["dailyPrecipitationMm"],
                    "observationRecordedAt": weather["observation"]["observedAt"],
                    "qualityFlag": weather["observation"]["qualityFlag"],
                },
            },
            {
                "sourceRole": "resolution_primary",
                "sourceRef": operations["sourceRef"],
                "normalizedFields": {
                    "weatherCodedDisruptionCount": sum(
                        1 for event in operations["events"] if event["weatherCoded"]
                    ),
                    "affectedStops": sum(event["affectedStops"] for event in operations["events"]),
                    "eventCodes": sorted({event["eventCode"] for event in operations["events"]}),
                    "coverageStatus": operations.get("coverageStatus", "complete"),
                },
            },
            {
                "sourceRole": "baseline_input",
                "sourceRef": baseline["sourceRef"],
                "normalizedFields": {
                    "lookbackStartsAt": baseline["lookbackStartsAt"],
                    "lookbackEndsAt": baseline["lookbackEndsAt"],
                    "weatherThresholdBucket": baseline["weatherThresholdBucket"],
                    "comparableServiceDays": baseline["comparableServiceDays"],
                    "disruptionDays": baseline["disruptionDays"],
                    "baselineProbability": baseline_probability(baseline),
                    "smoothing": baseline["smoothing"],
                },
            },
        ],
    }


def build_feature_snapshot(
    case: dict[str, Any],
    weather: dict[str, Any],
    baseline: dict[str, Any],
) -> dict[str, Any]:
    forecast_precipitation = float(weather["forecast"]["dailyPrecipitationMm"])
    threshold = float(case["precipitationThresholdMm"])
    base_probability = baseline_probability(baseline)
    return {
        "featureSnapshotId": case["featureSnapshotId"],
        "questionId": case["questionId"],
        "generatedAt": case["forecastedAt"],
        "domain": case["domain"],
        "horizon": case["horizon"],
        "sourceIds": [
            weather["forecastSourceRef"]["sourceId"],
            baseline["sourceRef"]["sourceId"],
        ],
        "features": {
            "forecastDailyPrecipitationMm": forecast_precipitation,
            "precipitationThresholdMm": threshold,
            "forecastExceedsThreshold": forecast_precipitation >= threshold,
            "baselineComparableServiceDays": baseline["comparableServiceDays"],
            "baselineDisruptionRate": base_probability,
            "routeDensity": case["routeDensity"],
        },
    }



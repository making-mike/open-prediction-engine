def build_resolution(
    case: dict[str, Any],
    question: dict[str, Any],
    operations: dict[str, Any],
    weather: dict[str, Any],
) -> dict[str, Any]:
    status = case.get("resolutionStatus", "resolved")
    supporting_evidence = [
        operations["sourceRef"]["uri"],
        weather["observationSourceRef"]["uri"],
    ]
    if status != "resolved":
        return {
            "resolutionRecordId": case["resolutionRecordId"],
            "questionId": case["questionId"],
            "status": status,
            "resolvedAt": case["resolvedAt"],
            "resolutionSource": question["primaryResolutionSource"],
            "resolutionAuthority": question["resolutionAuthority"],
            "unscorableReason": case["unscorableReason"],
            "supportingEvidence": supporting_evidence,
        }

    disruption_seen = any(event["weatherCoded"] for event in operations["events"])
    threshold_met = (
        float(weather["observation"]["dailyPrecipitationMm"])
        >= float(case["precipitationThresholdMm"])
    )
    return {
        "resolutionRecordId": case["resolutionRecordId"],
        "questionId": case["questionId"],
        "status": "resolved",
        "resolvedAt": case["resolvedAt"],
        "resolutionSource": question["primaryResolutionSource"],
        "resolutionAuthority": question["resolutionAuthority"],
        "resolvedOutcome": {
            "outputType": "binary",
            "value": bool(disruption_seen and threshold_met),
        },
        "supportingEvidence": supporting_evidence,
    }


def build_reports(
    case: dict[str, Any],
    question: dict[str, Any],
    evidence_packet: dict[str, Any],
    history: dict[str, Any],
    resolution: dict[str, Any],
) -> dict[str, Any]:
    prefix = output_prefix(case)
    case_generated_at = generated_at(case)
    if should_exclude_resolution(resolution):
        scoring_report = {
            "scoringReportId": case["scoringReportId"],
            "questionId": case["questionId"],
            "forecastId": case["forecastId"],
            "historyId": case["historyId"],
            "resolutionRecordId": case["resolutionRecordId"],
            "scoreStatus": "excluded",
            "scoringRule": "not_scored",
            "excludedReason": resolution["unscorableReason"],
            "generatedAt": case_generated_at,
        }
        return {
            f"{prefix}-scoring.generated.json": scoring_report,
        }

    forecast_score = score_forecast_output(
        evidence_packet["forecastOutput"],
        resolution["resolvedOutcome"],
        "brier",
    )
    baseline_score = score_forecast_output(
        evidence_packet["baselineForecast"],
        resolution["resolvedOutcome"],
        "brier",
    )
    lift = baseline_lift(forecast_score, baseline_score)
    scoring_report = {
        "scoringReportId": case["scoringReportId"],
        "questionId": case["questionId"],
        "forecastId": case["forecastId"],
        "historyId": case["historyId"],
        "resolutionRecordId": case["resolutionRecordId"],
        "scoreStatus": "scored",
        "scoringRule": "brier",
        "primaryScore": round_float(forecast_score),
        "higherIsBetter": False,
        "timeWeighting": {
            "method": "latest_only",
            "totalWeight": 1,
        },
        "baselineScore": round_float(baseline_score),
        "baselineLift": round_float(lift),
        "generatedAt": case_generated_at,
    }

    probability = evidence_packet["forecastOutput"]["probability"]
    outcome = bool(resolution["resolvedOutcome"]["value"])
    buckets = calibration_buckets([(probability, outcome)], bucket_count=10)
    calibration_summary = {
        "calibrationSummaryId": case["calibrationSummaryId"],
        "generatedAt": case_generated_at,
        "domain": case["domain"],
        "horizonBucket": case["horizon"]["label"],
        "outputType": "binary",
        "coveragePeriod": {
            "startsAt": question["openAt"],
            "endsAt": resolution["resolvedAt"],
        },
        "sampleSize": 1,
        "expectedCalibrationError": round_float(expected_calibration_error(buckets, 1)),
        "buckets": [
            {
                "lowerProbability": round_float(bucket["lowerProbability"]),
                "upperProbability": round_float(bucket["upperProbability"]),
                "count": bucket["count"],
                "meanForecastProbability": round_float(bucket["meanForecastProbability"]),
                "observedFrequency": round_float(bucket["observedFrequency"]),
            }
            for bucket in buckets
        ],
    }

    summary = track_record_summary(
        domain=case["domain"],
        horizon_bucket=case["horizon"]["label"],
        output_type="binary",
        scoring_rule="brier",
        scores=[forecast_score],
        baseline_scores=[baseline_score],
        n_ambiguous=0,
        n_annulled=0,
        n_forecasts=len(history["entries"]),
    )
    track_record_report = {
        "trackRecordReportId": case["trackRecordReportId"],
        "generatedAt": case_generated_at,
        "coveragePeriod": {
            "startsAt": question["openAt"],
            "endsAt": resolution["resolvedAt"],
        },
        "domain": summary["domain"],
        "horizonBucket": summary["horizonBucket"],
        "outputType": summary["outputType"],
        "counts": summary["counts"],
        "summary": {
            "primaryScoringRule": summary["summary"]["primaryScoringRule"],
            "primaryScore": round_float(summary["summary"]["primaryScore"]),
            "baselineScore": round_float(summary["summary"]["baselineScore"]),
            "baselineLift": round_float(summary["summary"]["baselineLift"]),
            "calibrationError": calibration_summary["expectedCalibrationError"],
            "lastUpdated": case_generated_at,
        },
        "scoreHistogram": [
            {
                "lower": 0,
                "upper": 0.5,
                "count": 1,
            }
        ],
        "slices": [],
    }

    return {
        f"{prefix}-scoring.generated.json": scoring_report,
        f"{prefix}-calibration.generated.json": calibration_summary,
        f"{prefix}-track-record.generated.json": track_record_report,
    }


def build_fixture_loop_for_source(source_dir: Path) -> dict[str, Any]:
    case = load_json(source_dir / "case.json")
    weather = load_json(source_dir / "weather.json")
    operations = load_json(source_dir / "operations.json")
    baseline = load_json(source_dir / "baseline-history.json")
    prefix = output_prefix(case)

    question = build_question(case, operations, weather)
    normalized_sources = build_normalized_sources(case, operations, weather, baseline)
    feature_snapshot = build_feature_snapshot(case, weather, baseline)
    base_forecast = {
        "outputType": "binary",
        "probability": baseline_probability(baseline),
    }
    forecast_output = {
        "outputType": "binary",
        "probability": model_probability(base_forecast["probability"], feature_snapshot),
    }
    evidence_packet = build_evidence_packet(
        case,
        question,
        weather,
        baseline,
        feature_snapshot,
        forecast_output,
        base_forecast,
    )
    artifact = build_forecast_artifact(case, question, evidence_packet)
    history = build_history(case, evidence_packet, base_forecast)
    resolution = build_resolution(case, question, operations, weather)
    reports = build_reports(case, question, evidence_packet, history, resolution)

    outputs = {
        f"{prefix}-question.generated.json": question,
        f"{prefix}-normalized-sources.generated.json": normalized_sources,
        f"{prefix}-feature-snapshot.generated.json": feature_snapshot,
        f"{prefix}-evidence.generated.json": evidence_packet,
        f"{prefix}-artifact.generated.json": artifact,
        f"{prefix}-history.generated.json": history,
        f"{prefix}-resolution.generated.json": resolution,
    }
    outputs.update(reports)
    validate_loop(case, outputs)
    return outputs


def build_fixture_loop() -> dict[str, Any]:
    outputs: dict[str, Any] = {}
    for source_dir in sorted(path for path in SOURCE_ROOT.iterdir() if path.is_dir()):
        case_outputs = build_fixture_loop_for_source(source_dir)
        duplicate_names = sorted(set(outputs).intersection(case_outputs))
        if duplicate_names:
            raise ValueError(f"duplicate generated fixture-loop output names: {duplicate_names}")
        outputs.update(case_outputs)
    return outputs


def validate_loop(case: dict[str, Any], outputs: dict[str, Any]) -> None:
    prefix = output_prefix(case)
    question = outputs[f"{prefix}-question.generated.json"]
    evidence = outputs[f"{prefix}-evidence.generated.json"]
    resolution = outputs[f"{prefix}-resolution.generated.json"]
    scoring = outputs[f"{prefix}-scoring.generated.json"]

    if not (parse_time(case["forecastedAt"]) <= parse_time(case["closeAt"]) < parse_time(case["resolvedAt"])):
        raise AssertionError("fixture loop timestamps must follow forecast <= close < resolved")

    expected_status = case.get("resolutionStatus", "resolved")
    if question["status"] != expected_status:
        raise AssertionError(f"fixture loop question should finish with status {expected_status!r}")
    if evidence["questionStatus"] != "open":
        raise AssertionError("forecast evidence should preserve the pre-close question status")
    if resolution["status"] != expected_status:
        raise AssertionError(f"fixture loop resolution should finish with status {expected_status!r}")
    if should_exclude_resolution(resolution):
        if scoring["scoreStatus"] != "excluded":
            raise AssertionError("unscorable fixture loop should produce an excluded scoring report")
        if "resolvedOutcome" in resolution:
            raise AssertionError("unscorable fixture loop must not include resolvedOutcome")
    else:
        if scoring["scoreStatus"] != "scored":
            raise AssertionError("resolved fixture loop should produce a scored report")
        if "resolvedOutcome" not in resolution:
            raise AssertionError("resolved fixture loop must include resolvedOutcome")

    forecast_source_ids = {
        source_ref["sourceId"] for source_ref in evidence["provenanceReferences"]
    }
    resolution_source_ids = {
        question["primaryResolutionSource"]["sourceId"],
        *[
            source_ref["sourceId"]
            for source_ref in question.get("fallbackResolutionSources", [])
        ],
    }
    leaked_source_ids = forecast_source_ids.intersection(resolution_source_ids)
    if leaked_source_ids:
        raise AssertionError(
            f"forecast inputs must not include future resolution sources: {sorted(leaked_source_ids)}"
        )


def write_outputs(outputs: dict[str, Any]) -> None:
    expected_names = set(outputs)
    for path in GENERATED.glob("*.generated.json"):
        if path.name not in expected_names:
            path.unlink()
    for filename, output in outputs.items():
        write_json(GENERATED / filename, output)
    print(f"generated {len(outputs)} fixture-loop outputs")


def check_outputs(outputs: dict[str, Any]) -> None:
    errors: list[str] = []
    expected_names = set(outputs)
    for path in sorted(GENERATED.glob("*.generated.json")):
        if path.name not in expected_names:
            errors.append(f"stale fixture-loop output: {path}")
    for filename, output in outputs.items():
        path = GENERATED / filename
        expected = render_json(output)
        if not path.exists():
            errors.append(f"missing fixture-loop output: {path}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(f"fixture-loop drift: {path}")
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("run `python3 scripts/run_fixture_loop.py --write` to update outputs", file=sys.stderr)
        raise SystemExit(1)
    print(f"checked {len(outputs)} fixture-loop outputs")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="write generated fixture-loop outputs instead of checking committed outputs",
    )
    args = parser.parse_args()
    outputs = build_fixture_loop()
    if args.write:
        write_outputs(outputs)
    else:
        check_outputs(outputs)


if __name__ == "__main__":
    main()

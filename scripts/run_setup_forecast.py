#!/usr/bin/env python3
"""Generate or check setup-aware forecast execution records."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from build_live_weather_evidence import horizon_for_service_date, resolution_criteria, resolution_time_for_service_date
from generate_source_intake import CASE_ORDER, build_fixture_cases, build_reports
from ope_schema import SPEC, validate_record
from select_setup_method import build_decisions


ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "spec" / "fixtures" / "generated" / "setup-forecast"
GENERATED_AT = "2026-06-06T18:05:00Z"
FORECASTED_AT = "2026-06-02T10:30:00Z"
PRECIPITATION_THRESHOLD_MM = 20.0
HEAVY_RAIN_PROBABILITY_ADJUSTMENT = 0.27

CASE_SUFFIX = {
    "accepted": "901",
    "accepted_partial": "902",
    "needs_confirmation": "903",
    "rejected": "904",
}


class SetupForecastError(Exception):
    pass


def render_json(data: Any) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_json(data), encoding="utf-8")


def case_slug(case: str) -> str:
    return case.replace("_", "-")


def output_prefix(case: str) -> str:
    return f"weather-logistics-{case_slug(case)}-setup"


def rel_output(case: str, suffix: str) -> str:
    return f"spec/fixtures/generated/setup-forecast/{output_prefix(case)}-{suffix}.generated.json"


def generated_path(case: str, suffix: str) -> Path:
    return GENERATED / f"{output_prefix(case)}-{suffix}.generated.json"


def source_ref(source: dict[str, Any]) -> dict[str, Any]:
    ref: dict[str, Any] = {
        "sourceId": source["sourceId"],
        "name": source["displayName"],
        "sourceType": source["sourceClass"],
    }
    if source.get("sourceRef") is not None:
        ref["uri"] = source["sourceRef"]
    retrieved_at = source["retrieval"]["retrievedAt"]
    if retrieved_at is not None:
        ref["retrievedAt"] = retrieved_at
    if source.get("contentHash"):
        ref["contentHash"] = source["contentHash"]
    return ref


def source_by_role(manifest: dict[str, Any], role: str) -> dict[str, Any] | None:
    matches = [source for source in manifest["sources"] if source["sourceRole"] == role]
    if not matches:
        return None
    if len(matches) > 1:
        raise SetupForecastError(f"expected at most one {role} source")
    return matches[0]


def baseline_probability(source: dict[str, Any]) -> float:
    positives = source["positiveOutcomeCount"]
    if positives is None:
        raise SetupForecastError("historical baseline source must include positiveOutcomeCount")
    return round((float(positives) + 1.0) / (float(source["rowCount"]) + 2.0), 4)


def baseline_features(source: dict[str, Any]) -> dict[str, Any]:
    return {
        "forecastSignalUsed": False,
        "baselineMethod": "source_intake_historical_frequency",
        "comparableServiceDays": source["rowCount"],
        "disruptionDays": source["positiveOutcomeCount"],
        "smoothing": "laplace_add_one",
        "sourceManifestId": None,
        "sourceId": source["sourceId"],
    }


def numeric_feature(source: dict[str, Any], field_name: str) -> float:
    summary = source.get("featureSummary")
    if summary is None:
        raise SetupForecastError(f"source {source['sourceId']} is missing feature summary")
    matches = [
        item["value"]
        for item in summary["numericValues"]
        if item["fieldName"] == field_name
    ]
    if len(matches) != 1:
        raise SetupForecastError(f"source {source['sourceId']} must include one {field_name} numeric feature")
    return float(matches[0])


def deterministic_probability(baseline_probability_value: float, weather_source: dict[str, Any]) -> tuple[float, float]:
    precipitation_mm = numeric_feature(weather_source, "forecast_daily_precipitation_mm")
    if precipitation_mm >= PRECIPITATION_THRESHOLD_MM:
        probability = min(0.95, baseline_probability_value + HEAVY_RAIN_PROBABILITY_ADJUSTMENT)
    else:
        probability = max(0.01, baseline_probability_value - 0.04)
    return round(probability, 4), precipitation_mm


def build_question(case: str, manifest: dict[str, Any], outcome_source: dict[str, Any]) -> dict[str, Any]:
    params = manifest["forecastParameters"]
    service_date = params["serviceDate"]
    geography = params["geography"]
    title = f"Will heavy rain disrupt last-mile delivery operations in {geography} on {service_date}?"
    horizon = horizon_for_service_date(service_date)
    return {
        "questionId": f"question-{CASE_SUFFIX[case]}",
        "title": title,
        "background": "Generated by setup-aware forecast execution from accepted source intake and setup method decision records.",
        "domain": manifest["domain"],
        "outputType": "binary",
        "status": "open",
        "openAt": FORECASTED_AT,
        "closeAt": params["forecastCloseTime"],
        "resolveAt": resolution_time_for_service_date(service_date),
        "horizon": horizon,
        "resolutionCriteria": resolution_criteria(geography, service_date, PRECIPITATION_THRESHOLD_MM),
        "resolutionAuthority": "OPE prototype resolver",
        "resolutionMode": "automated_measurement",
        "primaryResolutionSource": source_ref(outcome_source),
        "fallbackResolutionSources": [],
        "validOutcomeSpace": {
            "description": "Binary outcome: Yes if declared operations outcome says disruption_observed is true; No otherwise.",
            "labels": ["yes", "no"],
        },
        "clarificationHistory": [],
        "incentiveRiskReview": {
            "riskLevel": "minimal",
            "notes": "Setup-aware fixture forecast with no network access, live fetch, local live draft, or private-source runtime.",
        },
        "createdAt": FORECASTED_AT,
        "updatedAt": FORECASTED_AT,
    }


def build_feature_snapshot(
    case: str,
    manifest: dict[str, Any],
    report: dict[str, Any],
    decision: dict[str, Any],
    question: dict[str, Any],
    baseline_source: dict[str, Any],
    baseline_probability_value: float,
    forecast_probability: float,
    weather_source: dict[str, Any] | None = None,
    precipitation_mm: float | None = None,
) -> dict[str, Any]:
    features = baseline_features(baseline_source)
    features["sourceManifestId"] = manifest["sourceManifestId"]
    features["selectedMethodClass"] = decision["selectedMethodClass"]
    features["setupBenchmarkGateId"] = decision["selectedSetupBenchmarkGateId"]
    features["baselineProbability"] = baseline_probability_value
    features["forecastProbability"] = forecast_probability
    if weather_source is not None and precipitation_mm is not None:
        features["forecastSignalUsed"] = True
        features["weatherForecastSourceId"] = weather_source["sourceId"]
        features["forecastDailyPrecipitationMm"] = precipitation_mm
        features["precipitationThresholdMm"] = PRECIPITATION_THRESHOLD_MM
        features["heavyRainAdjustment"] = HEAVY_RAIN_PROBABILITY_ADJUSTMENT
    return {
        "featureSnapshotId": f"featuresnapshot-{CASE_SUFFIX[case]}",
        "domainSetupId": manifest["domainSetupId"],
        "sourceIntakeReportId": report["sourceIntakeReportId"],
        "setupMethodDecisionId": decision["setupMethodDecisionId"],
        "questionId": question["questionId"],
        "generatedAt": FORECASTED_AT,
        "domain": question["domain"],
        "horizon": question["horizon"],
        "sourceIds": [baseline_source["sourceId"], *([weather_source["sourceId"]] if weather_source else [])],
        "features": features,
    }


def model_identity(case: str, decision: dict[str, Any]) -> dict[str, Any]:
    if decision["selectedMethodClass"] == "deterministic_statistical":
        return {
            "modelId": "model-101",
            "version": "weather-logistics-fixture-loop-v0",
            "trainingCutoff": "2026-05-30T00:00:00Z",
            "configurationHash": "sha256-fixture-loop-model-001",
        }
    return {
        "modelId": f"model-{CASE_SUFFIX[case]}",
        "version": "setup-aware-historical-baseline-fixture-v1",
        "configurationHash": f"sha256-setup-forecast-model-{CASE_SUFFIX[case]}",
    }


def build_evidence_packet(
    case: str,
    manifest: dict[str, Any],
    report: dict[str, Any],
    decision: dict[str, Any],
    question: dict[str, Any],
    baseline_source: dict[str, Any],
    baseline_probability_value: float,
    forecast_probability: float,
    weather_source: dict[str, Any] | None = None,
    precipitation_mm: float | None = None,
) -> dict[str, Any]:
    forecast_output = {
        "outputType": "binary",
        "probability": forecast_probability,
    }
    baseline_output = {
        "outputType": "binary",
        "probability": baseline_probability_value,
    }
    sample_size = baseline_source["rowCount"]
    provenance = [source_ref(baseline_source), *([source_ref(weather_source)] if weather_source else [])]
    input_source_classes = []
    for source in [baseline_source, *([weather_source] if weather_source else [])]:
        if source["sourceClass"] not in input_source_classes:
            input_source_classes.append(source["sourceClass"])
    if decision["selectedMethodClass"] == "deterministic_statistical":
        rationale = (
            "Setup-aware execution selected a deterministic statistical method because the setup benchmark gate "
            "approved fixture execution with clean comparable benchmark evidence; quality claims remain blocked."
        )
    else:
        rationale = (
            "Setup-aware execution selected the historical baseline because stronger methods are not enabled for this intake."
        )
    key_factors = [
        f"source intake report {report['sourceIntakeReportId']}",
        f"setup method decision {decision['setupMethodDecisionId']}",
        f"selected method {decision['selectedMethodClass']}",
        f"historical disruption days {baseline_source['positiveOutcomeCount']}",
        f"comparable service days {baseline_source['rowCount']}",
    ]
    if decision["selectedSetupBenchmarkGateId"] is not None:
        key_factors.append(f"setup benchmark gate {decision['selectedSetupBenchmarkGateId']}")
    if precipitation_mm is not None:
        key_factors.append(f"forecast precipitation {precipitation_mm:g} mm")
    key_factors.append("no local live draft consumed")
    return {
        "evidencePacketId": f"evidence-{CASE_SUFFIX[case]}",
        "forecastId": f"forecast-{CASE_SUFFIX[case]}",
        "questionId": question["questionId"],
        "questionStatus": "open",
        "domain": question["domain"],
        "horizon": question["horizon"],
        "forecastedAt": FORECASTED_AT,
        "model": model_identity(case, decision),
        "inputSourceClasses": input_source_classes,
        "provenanceReferences": provenance,
        "featureSnapshotRef": f"https://example.test/fixtures/generated/setup-forecast/{output_prefix(case)}-feature-snapshot.generated.json",
        "forecastOutput": forecast_output,
        "baselineForecast": baseline_output,
        "calibrationBand": {
            "lower": round(max(0.0, forecast_probability - 0.1), 4),
            "upper": round(min(1.0, forecast_probability + 0.1), 4),
            "coverage": 0.8,
            "sampleSize": sample_size,
        },
        "rationaleSummary": rationale,
        "keyFactors": key_factors,
        "resolutionCriteria": question["resolutionCriteria"],
        "resolutionSource": question["primaryResolutionSource"],
        "fallbackResolutionSources": question["fallbackResolutionSources"],
        "scheduledResolutionAt": question["resolveAt"],
    }



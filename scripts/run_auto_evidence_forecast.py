ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "spec" / "fixtures" / "generated" / "auto-evidence"
FORECASTED_AT = "2026-06-02T10:00:00Z"
GENERATED_AT = "2026-06-02T10:02:00Z"


class AutoEvidenceForecastError(Exception):
    pass


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_json(data), encoding="utf-8")


def source_record(source_set: dict[str, Any], role: str) -> dict[str, Any]:
    matches = [record for record in source_set["records"] if record["sourceRole"] == role]
    if len(matches) != 1:
        raise AutoEvidenceForecastError(f"expected one {role} source record")
    return matches[0]


def normalized_weather_from_source_set(source_set: dict[str, Any]) -> dict[str, Any]:
    record = source_record(source_set, "forecast_input")
    return {
        "sourceRef": record["sourceRef"],
        "provider": "Open-Meteo",
        "geography": source_set["geography"],
        "serviceDate": source_set["serviceDate"],
        "sourceStatus": record["sourceQuality"]["status"],
        "correctionReviewRequired": record["sourceQuality"]["status"] == "corrected",
        "normalizedFields": record["normalizedFields"],
    }


def baseline_history_from_source_set(source_set: dict[str, Any]) -> dict[str, Any]:
    record = source_record(source_set, "baseline_input")
    fields = record["normalizedFields"]
    return {
        "sourceRef": record["sourceRef"],
        "geography": source_set["geography"],
        "lookbackStartsAt": fields["lookbackStartsAt"],
        "lookbackEndsAt": fields["lookbackEndsAt"],
        "weatherThresholdBucket": fields["weatherThresholdBucket"],
        "comparableServiceDays": fields["comparableServiceDays"],
        "disruptionDays": fields["disruptionDays"],
        "smoothing": fields["smoothing"],
    }


def source_ref(source_id: str, name: str, source_type: str) -> dict[str, str]:
    return {
        "sourceId": source_id,
        "name": name,
        "sourceType": source_type,
    }


def build_question(request: dict[str, Any], baseline: dict[str, Any]) -> dict[str, Any]:
    service_date = request["serviceDate"]
    geography = request["geography"]
    threshold = float(baseline["features"]["precipitationThresholdMm"])
    horizon = horizon_for_service_date(service_date)
    operations_source = source_ref("source-402", "Declared Warsaw operations event source", "internal_dataset")
    weather_observation_source = source_ref(
        "source-403",
        "Open-Meteo weather observation for Warsaw",
        "public_dataset",
    )
    return {
        "questionId": "question-601",
        "title": request["questionText"],
        "background": "Generated by the auto-evidence fixture-replay forecast path for the selected weather-logistics wedge.",
        "domain": request["domain"],
        "outputType": request["outputType"],
        "status": "open",
        "openAt": FORECASTED_AT,
        "closeAt": f"{service_date}T00:00:00Z",
        "resolveAt": resolution_time_for_service_date(service_date),
        "horizon": horizon,
        "resolutionCriteria": resolution_criteria(geography, service_date, threshold),
        "resolutionAuthority": "OPE prototype resolver",
        "resolutionMode": "automated_measurement",
        "primaryResolutionSource": operations_source,
        "fallbackResolutionSources": [weather_observation_source],
        "validOutcomeSpace": {
            "description": "Binary outcome: Yes if disruption and precipitation criteria are both satisfied; No otherwise.",
            "labels": ["yes", "no"],
        },
        "clarificationHistory": [],
        "incentiveRiskReview": {
            "riskLevel": "minimal",
            "notes": "Auto-evidence fixture-replay forecast with no live fetch or private operational data.",
        },
        "createdAt": FORECASTED_AT,
        "updatedAt": FORECASTED_AT,
    }



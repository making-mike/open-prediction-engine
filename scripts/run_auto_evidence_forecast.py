def output_prefix() -> str:
    return "weather-logistics-auto-evidence"


def build_outputs(request_path: Path = DEFAULT_REQUEST) -> dict[str, Any]:
    request = load_json(request_path)
    decision = validate_request(request)
    if decision["decisionStatus"] != "accepted":
        raise AutoEvidenceForecastError(f"request was {decision['decisionStatus']}")
    if request["requestedAction"] != "generate_forecast":
        raise AutoEvidenceForecastError("auto-evidence forecast requires requestedAction generate_forecast")
    plan = build_plan(request_path)
    source_set = build_source_set(request_path)
    normalized_weather = normalized_weather_from_source_set(source_set)
    baseline_history = baseline_history_from_source_set(source_set)
    baseline = build_baseline_record(
        normalized_weather=normalized_weather,
        baseline_history=baseline_history,
        generated_at=FORECASTED_AT,
    )
    question = build_question(request, baseline)
    feature_snapshot = build_feature_snapshot(request, question, baseline, source_set)
    forecast_output = {
        "outputType": "binary",
        "probability": model_probability(baseline),
    }
    evidence = build_evidence_packet(request, plan, source_set, question, baseline, forecast_output)
    artifact = build_forecast_artifact(question, evidence)
    history = build_history(baseline, evidence, question)
    pipeline_run = build_pipeline_run(request, decision, plan, source_set, question, evidence, history)
    prefix = output_prefix()
    outputs = {
        f"{prefix}-pipeline-run.generated.json": pipeline_run,
        f"{prefix}-question.generated.json": question,
        f"{prefix}-feature-snapshot.generated.json": feature_snapshot,
        f"{prefix}-evidence.generated.json": evidence,
        f"{prefix}-artifact.generated.json": artifact,
        f"{prefix}-history.generated.json": history,
    }
    validate_outputs(outputs, plan, source_set)
    return outputs


def validate_outputs(outputs: dict[str, Any], plan: dict[str, Any], source_set: dict[str, Any]) -> None:
    schemas = {
        "weather-logistics-auto-evidence-pipeline-run.generated.json": "pipeline-run.schema.json",
        "weather-logistics-auto-evidence-question.generated.json": "forecast-question.schema.json",
        "weather-logistics-auto-evidence-evidence.generated.json": "evidence-packet.schema.json",
        "weather-logistics-auto-evidence-artifact.generated.json": "forecast-artifact.schema.json",
        "weather-logistics-auto-evidence-history.generated.json": "forecast-history.schema.json",
    }
    for filename, schema_name in schemas.items():
        errors = validate_record(outputs[filename], SPEC / schema_name)
        if errors:
            raise AutoEvidenceForecastError(f"{filename} failed schema validation: {errors[0]}")

    pipeline_run = outputs["weather-logistics-auto-evidence-pipeline-run.generated.json"]
    question = outputs["weather-logistics-auto-evidence-question.generated.json"]
    evidence = outputs["weather-logistics-auto-evidence-evidence.generated.json"]
    artifact = outputs["weather-logistics-auto-evidence-artifact.generated.json"]
    history = outputs["weather-logistics-auto-evidence-history.generated.json"]

    if pipeline_run["outputs"]["evidencePlanId"] != plan["evidencePlanId"]:
        raise AutoEvidenceForecastError("pipeline run/evidence plan binding mismatch")
    if pipeline_run["outputs"]["evidenceSourceSetId"] != source_set["evidenceSourceSetId"]:
        raise AutoEvidenceForecastError("pipeline run/source set binding mismatch")
    if pipeline_run["outputs"]["sourcePolicyId"] != plan["sourcePolicy"]["sourcePolicyId"]:
        raise AutoEvidenceForecastError("pipeline run/source policy binding mismatch")
    if artifact["forecastId"] != evidence["forecastId"]:
        raise AutoEvidenceForecastError("artifact/evidence forecast binding mismatch")
    if artifact["questionId"] != question["questionId"]:
        raise AutoEvidenceForecastError("artifact/question binding mismatch")
    if history["entries"][-1]["forecastId"] != evidence["forecastId"]:
        raise AutoEvidenceForecastError("history must end with generated auto-evidence forecast")
    if pipeline_run["effectfulGeneration"] is not False:
        raise AutoEvidenceForecastError("auto-evidence forecast must not claim effectful generation")
    if pipeline_run["controls"]["liveFetch"] is not False:
        raise AutoEvidenceForecastError("auto-evidence forecast must not live-fetch")

    forecast_source_ids = {source["sourceId"] for source in evidence["provenanceReferences"]}
    resolution_source_ids = {
        question["primaryResolutionSource"]["sourceId"],
        *[source["sourceId"] for source in question["fallbackResolutionSources"]],
    }
    if forecast_source_ids.intersection(resolution_source_ids):
        raise AutoEvidenceForecastError("forecast provenance must not include future resolution sources")


def write_outputs(outputs: dict[str, Any]) -> None:
    for filename, output in outputs.items():
        write_json(GENERATED / filename, output)
    print(f"generated {len(outputs)} auto-evidence forecast outputs")


def check_outputs(outputs: dict[str, Any]) -> None:
    errors: list[str] = []
    for filename, output in outputs.items():
        path = GENERATED / filename
        expected = render_json(output)
        if not path.exists():
            errors.append(f"missing auto-evidence forecast output: {path}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(f"auto-evidence forecast drift: {path}")
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print("run `python3 scripts/run_auto_evidence_forecast.py --write`", file=sys.stderr)
        raise SystemExit(1)
    print(f"checked {len(outputs)} auto-evidence forecast outputs")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--request", type=Path, default=DEFAULT_REQUEST)
    parser.add_argument("--write", action="store_true", help="write generated auto-evidence forecast outputs")
    args = parser.parse_args()
    try:
        outputs = build_outputs(args.request)
    except AutoEvidenceForecastError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
    if args.write:
        write_outputs(outputs)
    else:
        check_outputs(outputs)


if __name__ == "__main__":
    main()
